-- Phase 9.4–9.6: LSPD – MDT (Einträge, Fahndungen, Berichte), Einsätze, Haft, Beschlagnahme
CREATE TABLE IF NOT EXISTS mdt_records (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  character_id INT UNSIGNED NOT NULL,
  officer_id INT UNSIGNED NULL,
  officer_name VARCHAR(64) NOT NULL,
  offense VARCHAR(255) NOT NULL,
  fine INT UNSIGNED NOT NULL DEFAULT 0,
  jail_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_mdt_records_char (character_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mdt_warrants (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  kind ENUM('person','vehicle') NOT NULL,
  character_id INT UNSIGNED NULL,
  plate VARCHAR(8) NULL,
  reason VARCHAR(255) NOT NULL,
  officer_name VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMP NULL DEFAULT NULL,
  closed_by VARCHAR(64) NULL,
  KEY idx_mdt_warrants_open (closed_at, kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mdt_reports (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  officer_name VARCHAR(64) NOT NULL,
  title VARCHAR(96) NOT NULL,
  text TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mdt_queries (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  officer_id INT UNSIGNED NOT NULL,
  kind VARCHAR(16) NOT NULL,
  query VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE characters ADD COLUMN IF NOT EXISTS jail_seconds INT UNSIGNED NOT NULL DEFAULT 0;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS seized_fee INT UNSIGNED NOT NULL DEFAULT 0;

-- Fraktionen bekommen eine Zahl für Konto und Lager (owner_id ist numerisch)
ALTER TABLE factions ADD COLUMN IF NOT EXISTS num INT UNSIGNED NOT NULL AUTO_INCREMENT, ADD UNIQUE KEY IF NOT EXISTS uq_factions_num (num);
