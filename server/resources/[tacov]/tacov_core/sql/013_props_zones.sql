CREATE TABLE IF NOT EXISTS props (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  label VARCHAR(64) NOT NULL DEFAULT '',
  model VARCHAR(64) NOT NULL,
  x DOUBLE NOT NULL, y DOUBLE NOT NULL, z DOUBLE NOT NULL,
  rx DOUBLE NOT NULL DEFAULT 0, ry DOUBLE NOT NULL DEFAULT 0, rz DOUBLE NOT NULL DEFAULT 0,
  on_ground TINYINT(1) NOT NULL DEFAULT 1,
  updated_by VARCHAR(32) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS zones (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  label VARCHAR(64) NOT NULL DEFAULT '',
  kind VARCHAR(24) NOT NULL DEFAULT 'area',
  shape VARCHAR(8) NOT NULL DEFAULT 'circle',   -- circle | poly
  points TEXT NOT NULL,                         -- JSON: [{x,y}] (circle: ein Punkt)
  radius DOUBLE NOT NULL DEFAULT 20,
  z_min DOUBLE NULL, z_max DOUBLE NULL,
  updated_by VARCHAR(32) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
